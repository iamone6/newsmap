    ('뉴스1',    '{뉴스1,News1}'),
    ('AP',       '{AP,AP통신,AP연합}'),
    ('AFP',      '{AFP,AFP통신,AFP연합}'),
    ('로이터',   '{로이터,Reuters,로이터연합}'),
    ('EPA',      '{EPA,EPA연합}');

-- -----------------------------------------------------------------------------
-- 섹션 (대분류 6개 고정)
-- -----------------------------------------------------------------------------
CREATE TABLE sections (
    id   smallint PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL UNIQUE
);

