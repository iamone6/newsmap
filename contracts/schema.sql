-- =============================================================================
-- newsmap RAG schema
--   PostgreSQL 18.6 / pgvector 0.8.6 / pg_search 0.25.11
--   적용: psql -v ON_ERROR_STOP=1 -f contracts/schema.sql  (README 참고)
--   시각: 모두 timestamptz(0), DB 시간대 Asia/Seoul (초 단위까지 저장)
