BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_search;

-- -----------------------------------------------------------------------------
-- 행정구역 마스터 (행정안전부 행정표준코드, 행정동 10자리)
--   코드 구조: 시도(2) + 시군구(3) + 읍면동(3) + 리(2)
--   폐지된 코드도 삭제하지 않고 valid_to 만 채운다.
-- -----------------------------------------------------------------------------
CREATE TABLE regions (
    code         varchar(10) PRIMARY KEY,
    level        smallint    NOT NULL CHECK (level IN (1, 2, 3)),  -- 1 시도, 2 시군구, 3 읍면동
    sido_name    text        NOT NULL,
    sigungu_name text,
    emd_name     text,
    full_name    text        NOT NULL,                             -- 예: 경기도 수원시 영통구 매탄1동
    parent_code  varchar(10) REFERENCES regions (code),
    valid_from   date,
    valid_to     date                                              -- NULL 이면 현재 유효
);

CREATE INDEX regions_parent_code_idx ON regions (parent_code);
CREATE INDEX regions_full_name_idx ON regions (full_name);

-- -----------------------------------------------------------------------------
-- 통신사 (자사 생산 여부 / 이미지 라이선스 판단용 정규화 테이블)
-- -----------------------------------------------------------------------------
CREATE TABLE wire_agencies (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text   NOT NULL UNIQUE,                 -- 정규화된 이름
    aliases text[] NOT NULL DEFAULT '{}'            -- 기사/캡션에 나타나는 표기들
);

CREATE INDEX wire_agencies_aliases_idx ON wire_agencies USING gin (aliases);

